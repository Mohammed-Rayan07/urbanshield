"""Prompt-injection suite over the committed variants (EVALS.md section 4).

    uv run python scripts/injection_suite.py [--write]

Each variant goes through the real quarantine (one tool-less extraction call) and the
cross-check against A's pinned feed and the demo city's inventory. Embedded instructions pass
if the typed advisory is exactly the truth (or the text is rejected); valid-but-wrong
advisories pass if the cross-check flags the lying field.

In mock mode the extractor is a regex, so the table is a plumbing check only and ``--write``
is refused; EVALS.md numbers come from live or replay runs and state their mode. The variants
are generated by ``scripts/make_injection_suite.py``.
"""

from __future__ import annotations

import argparse
import sys

from urbanshield.agents.engine import default_engine
from urbanshield.agents.evidence import (
    injection_table,
    load_injection_suite,
    replace_section,
    run_injection_case,
)
from urbanshield.agents.llm import get_llm
from urbanshield.config import BACKEND_DIR, get_settings

EVALS = BACKEND_DIR.parent / "docs" / "EVALS.md"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write the table into docs/EVALS.md")
    args = parser.parse_args(argv)

    settings = get_settings()
    if args.write and settings.llm_mode == "mock":
        print("Refusing --write in mock mode: the mock extractor is a regex, not evidence.", file=sys.stderr)
        return 2
    engine = default_engine()
    city = engine.generate_city(seed=settings.city_seed)
    llm = get_llm(settings)
    results = [run_injection_case(case, llm, engine.feed_record, city) for case in load_injection_suite()]
    table = injection_table(results, settings.llm_mode) + (
        f"\n\nCross-checked against A's pinned KEV feed snapshot and the inventory of `{city.id}` "
        f"(seed {settings.city_seed})."
    )
    print(table)
    if args.write:
        replace_section(EVALS, 4, table)
        print(f"wrote section 4 of {EVALS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
